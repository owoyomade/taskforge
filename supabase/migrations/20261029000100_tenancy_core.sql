-- Phase 1: identity and tenancy core.
--
-- Every tenant-owned table in Taskforge belongs to a workspace, and every Row
-- Level Security (RLS) policy asks the same question: "is the signed-in user a
-- member of this row's workspace, and with what role?" The helper functions in
-- this file answer that question in one place so later tables (projects,
-- tasks, ...) can reuse them.
--
-- Conventions:
--   * Business-rule violations raise SQLSTATE 'TF001'. Their messages are
--     written for end users, so the app may show them as-is.
--   * Security definer functions pin search_path to '' and use fully
--     qualified names, so a malicious object on the search path can't hijack them.

create type public.workspace_role as enum ('owner', 'admin', 'member', 'viewer');

create function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Profiles: the public face of an auth user. auth.users itself is not exposed
-- to the browser, so anything teammates need to see (name, email, avatar)
-- lives here.
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  full_name text not null default '' check (char_length(full_name) <= 80),
  -- Storage object path inside the private "avatars" bucket. It must sit in
  -- the user's own folder so nobody can point their avatar at someone else's file.
  avatar_path text check (
    avatar_path is null
    or (avatar_path like id::text || '/%' and char_length(avatar_path) <= 200)
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

-- Creates the profile row as soon as Supabase Auth creates the user, so the
-- app never has to handle "user exists but profile doesn't".
create function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    coalesce(new.email, ''),
    left(trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), 80)
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

-- Keeps profiles.email in step when a user confirms an email change.
create function public.handle_auth_user_email_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles set email = coalesce(new.email, '') where id = new.id;
  return new;
end;
$$;

create trigger on_auth_user_email_changed
  after update of email on auth.users
  for each row
  when (old.email is distinct from new.email)
  execute function public.handle_auth_user_email_change();

-- ---------------------------------------------------------------------------
-- Workspaces and memberships
-- ---------------------------------------------------------------------------

create table public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 2 and 60),
  -- URL-safe identifier used in /w/<slug>. Generated by the app, never edited.
  slug text not null unique check (
    slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) between 3 and 64
  ),
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger workspaces_set_updated_at
  before update on public.workspaces
  for each row execute function public.set_updated_at();

create table public.workspace_members (
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  role public.workspace_role not null default 'member',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

-- The primary key already serves lookups by workspace; this one serves
-- "which workspaces is this user in?", which runs on almost every request.
create index workspace_members_user_id_idx on public.workspace_members (user_id);

create trigger workspace_members_set_updated_at
  before update on public.workspace_members
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- Authorization helpers
--
-- These are SECURITY DEFINER so they can read workspace_members without
-- triggering workspace_members' own RLS policies (which would otherwise call
-- these functions again and recurse forever). They only ever answer questions
-- about the *current* user, so they can't be used to probe other people.
-- ---------------------------------------------------------------------------

create function public.workspace_role_for(target_workspace uuid)
returns public.workspace_role
language sql
stable
security definer
set search_path = ''
as $$
  select role
  from public.workspace_members
  where workspace_id = target_workspace
    and user_id = (select auth.uid());
$$;

create function public.is_workspace_member(target_workspace uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.workspace_role_for(target_workspace) is not null;
$$;

create function public.has_workspace_role(
  target_workspace uuid,
  allowed_roles public.workspace_role[]
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(public.workspace_role_for(target_workspace) = any (allowed_roles), false);
$$;

-- True when the current user and other_user have at least one workspace in
-- common. Used to decide whose profile and avatar you're allowed to see.
create function public.shares_workspace_with(other_user uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.workspace_members as mine
    join public.workspace_members as theirs using (workspace_id)
    where mine.user_id = (select auth.uid())
      and theirs.user_id = other_user
  );
$$;

-- ---------------------------------------------------------------------------
-- Membership rules that RLS alone can't express
-- ---------------------------------------------------------------------------

-- Runs before any role change or removal and enforces:
--   1. Only owners can grant, change, or remove the owner role.
--   2. A workspace always keeps at least one owner.
-- Removing members because the whole workspace is being deleted is allowed.
create function public.enforce_membership_rules()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor_role public.workspace_role;
  touches_owner boolean;
begin
  -- Lock the workspace row so two concurrent changes can't both see "another
  -- owner exists" and leave the workspace with none.
  perform 1 from public.workspaces where id = old.workspace_id for update;

  if not found then
    -- The workspace itself is being deleted and this row is going with it.
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  touches_owner := old.role = 'owner' or (tg_op = 'UPDATE' and new.role = 'owner');

  -- auth.uid() is null for trusted maintenance (migrations, seeds, service
  -- role); rule 1 only applies to signed-in users acting through the API.
  if touches_owner and auth.uid() is not null then
    actor_role := public.workspace_role_for(old.workspace_id);
    if actor_role is distinct from 'owner' then
      raise exception 'Only an owner can change or remove an owner.'
        using errcode = 'TF001';
    end if;
  end if;

  if old.role = 'owner' and (tg_op = 'DELETE' or new.role <> 'owner') then
    if not exists (
      select 1
      from public.workspace_members
      where workspace_id = old.workspace_id
        and role = 'owner'
        and user_id <> old.user_id
    ) then
      raise exception 'A workspace must keep at least one owner. Make someone else an owner first.'
        using errcode = 'TF001';
    end if;
  end if;

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

create trigger workspace_members_enforce_rules
  before update or delete on public.workspace_members
  for each row execute function public.enforce_membership_rules();

-- ---------------------------------------------------------------------------
-- Creating a workspace
--
-- There is no INSERT policy on workspaces or workspace_members. New
-- workspaces go through this function so the workspace and its first owner
-- are created together in one transaction; otherwise there would be a moment
-- where a workspace exists with nobody allowed to see it.
-- ---------------------------------------------------------------------------

create function public.create_workspace(workspace_name text, workspace_slug text)
returns public.workspaces
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller uuid := auth.uid();
  owned_count integer;
  created public.workspaces;
begin
  if caller is null then
    raise exception 'You must be signed in to create a workspace.' using errcode = '42501';
  end if;

  -- Basic abuse guard for the free tier. Raise it when paid plans exist.
  select count(*) into owned_count
  from public.workspace_members
  where user_id = caller and role = 'owner';

  if owned_count >= 10 then
    raise exception 'You can own up to 10 workspaces.' using errcode = 'TF001';
  end if;

  insert into public.workspaces (name, slug, created_by)
  values (trim(workspace_name), workspace_slug, caller)
  returning * into created;

  insert into public.workspace_members (workspace_id, user_id, role)
  values (created.id, caller, 'owner');

  return created;
end;
$$;

-- ---------------------------------------------------------------------------
-- Privileges
--
-- RLS decides *which rows* a user can touch; column grants decide *which
-- columns*. Together they stop, for example, a user rewriting their own
-- profile email or a workspace's slug through the public API.
-- ---------------------------------------------------------------------------

revoke all on public.profiles, public.workspaces, public.workspace_members from anon, authenticated;

grant select on public.profiles, public.workspaces, public.workspace_members to authenticated;
grant update (full_name, avatar_path) on public.profiles to authenticated;
grant update (name) on public.workspaces to authenticated;
grant delete on public.workspaces to authenticated;
grant update (role) on public.workspace_members to authenticated;
grant delete on public.workspace_members to authenticated;

revoke execute on function
  public.workspace_role_for(uuid),
  public.is_workspace_member(uuid),
  public.has_workspace_role(uuid, public.workspace_role[]),
  public.shares_workspace_with(uuid),
  public.create_workspace(text, text)
from public, anon;

grant execute on function
  public.workspace_role_for(uuid),
  public.is_workspace_member(uuid),
  public.has_workspace_role(uuid, public.workspace_role[]),
  public.shares_workspace_with(uuid),
  public.create_workspace(text, text)
to authenticated;

-- Trigger functions are only ever called by Postgres itself.
revoke execute on function
  public.handle_new_auth_user(),
  public.handle_auth_user_email_change(),
  public.enforce_membership_rules()
from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------

alter table public.profiles enable row level security;
alter table public.workspaces enable row level security;
alter table public.workspace_members enable row level security;

create policy "profiles: read own or teammates"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()) or public.shares_workspace_with(id));

create policy "profiles: update own"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "workspaces: members can read"
  on public.workspaces for select to authenticated
  using (public.is_workspace_member(id));

create policy "workspaces: owners and admins can rename"
  on public.workspaces for update to authenticated
  using (public.has_workspace_role(id, array['owner', 'admin']::public.workspace_role[]))
  with check (public.has_workspace_role(id, array['owner', 'admin']::public.workspace_role[]));

create policy "workspaces: owners can delete"
  on public.workspaces for delete to authenticated
  using (public.has_workspace_role(id, array['owner']::public.workspace_role[]));

create policy "workspace_members: members can read their workspace roster"
  on public.workspace_members for select to authenticated
  using (public.is_workspace_member(workspace_id));

create policy "workspace_members: owners and admins can change roles"
  on public.workspace_members for update to authenticated
  using (public.has_workspace_role(workspace_id, array['owner', 'admin']::public.workspace_role[]))
  with check (public.has_workspace_role(workspace_id, array['owner', 'admin']::public.workspace_role[]));

create policy "workspace_members: owners and admins remove members, anyone can leave"
  on public.workspace_members for delete to authenticated
  using (
    user_id = (select auth.uid())
    or public.has_workspace_role(workspace_id, array['owner', 'admin']::public.workspace_role[])
  );
